export const catalogs: Record<Locale, MessageCatalog> = { en, de };
export const supportedLocales: readonly Locale[] = ["en", "de"];

export function translate(
  locale: Locale,
  id: MessageId,
  values: Record<string, string | number> = {},
): string {
  const template = catalogs[locale][id] ?? en[id];
  return template.replace(/\{([^}]+)\}/g, (placeholder, key: string) =>
    key in values ? String(values[key]) : placeholder);
}

export function translatePlural(
  locale: Locale,
  key: string,
  count: number,
): string {
  const category = new Intl.PluralRules(locale).select(count);
  return translate(locale, `${key}.${category}` as MessageId, { count });
}
